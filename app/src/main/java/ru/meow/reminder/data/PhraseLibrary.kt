    val builtIn: List<CustomPhrase> = groups.flatMapIndexed { index, text ->
        text.lines().mapIndexed { i, line -> CustomPhrase("builtin-$index-$i", line, categories[index]) }
    }

    suspend fun pick(store: SettingsStore, custom: List<CustomPhrase>, hour: Int = LocalTime.now().hour): String {
        val settings = store.get()
        if (!settings.phrases) return ""
        val pool = (builtIn + custom).filter {
            it.category in settings.categories && when (it.category) {
                "Доброе утро" -> hour in 5..11
                "Доброй ночи" -> hour >= 21 || hour < 5
                else -> true
            }
        }
        val candidates = pool.filter { it.id !in settings.recentPhrases }.ifEmpty { pool }
        val phrase = candidates.randomOrNull(Random.Default) ?: return ""
        store.update { it.copy(recentPhrases = (it.recentPhrases + phrase.id).takeLast(20)) }
        return phrase.text
    }
